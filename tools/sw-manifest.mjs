#!/usr/bin/env node
// Generates webroot/sw.js with the COMPLETE shell module graph embedded.
// The precache list is derived from the real files on disk (walk app/,
// vendor/, styles/, app-icons/) — nothing runtime-fetched, nothing missing.
// The cache version is a content hash of all shell files, so any change
// produces a new immutable cache name ("consistent version release").
// Run after any shell change: node tools/sw-manifest.mjs
import { createHash } from 'node:crypto';
import { readdirSync, statSync, readFileSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';

const ROOT = new URL('..', import.meta.url).pathname;      // repo root
const WEB = join(ROOT, 'webroot');

function walk(dir, out = []) {
  for (const name of readdirSync(dir).sort()) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p, out);
    else out.push(p);
  }
  return out;
}

const dirs = ['app', 'vendor', 'styles', 'app-icons'];
const files = [];
for (const d of dirs) {
  for (const p of walk(join(WEB, d))) files.push('/' + relative(WEB, p));
}
files.push('/', '/index.html', '/manifest.webmanifest');

// deterministic hash over path+content → immutable cache identity
const h = createHash('sha256');
for (const f of files.sort()) {
  h.update(f);
  if (f === '/') h.update(readFileSync(join(WEB, 'index.html')));
  else h.update(readFileSync(join(WEB, f.slice(1))));
}
const VERSION = `wish-web-shell-${h.digest('hex').slice(0, 16)}`;

const body = `// GENERATED by tools/sw-manifest.mjs — do not edit by hand.
// App-shell precache: the full module graph, versioned by content hash.
//   · cache-first for shell files (immutable per version; updates arrive as
//     a NEW service worker — never a mixed in-place mutation);
//   · activation only after the user confirms (SKIP_WAITING message from
//     the update prompt) — no mixed versions;
//   · /wishd-api/* and every non-GET: always live, never cached;
//   · only caches in THIS app's namespace (wish-web-shell-*) are managed.
const VERSION = '${VERSION}';
const SHELL = ${JSON.stringify(files.sort(), null, 2)};

self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(VERSION).then((c) => c.addAll(SHELL)));
});

self.addEventListener('activate', (e) => {
  e.waitUntil((async () => {
    for (const k of await caches.keys()) {
      if (k.startsWith('wish-web-shell-') && k !== VERSION) await caches.delete(k);
    }
    await self.clients.claim();
  })());
});

self.addEventListener('message', (e) => {
  if (e.data?.type === 'SKIP_WAITING') self.skipWaiting();
});

self.addEventListener('fetch', (e) => {
  const url = new URL(e.request.url);
  if (e.request.method !== 'GET') return;                    // mutations: live
  if (url.pathname.startsWith('/wishd-api/')) return;        // API: live only
  if (url.origin !== location.origin) return;
  const isShell = SHELL.includes(url.pathname)
    || (e.request.mode === 'navigate' && (url.pathname === '/' || url.pathname === '/index.html'));
  if (!isShell) return;                                      // everything else: live
  e.respondWith((async () => {
    const cache = await caches.open(VERSION);
    const hit = await cache.match(url.pathname === '/' ? '/index.html' : e.request, { ignoreSearch: true });
    if (hit) return hit;
    const res = await fetch(e.request);
    if (res.ok) cache.put(e.request, res.clone());
    return res;
  })());
});
`;
writeFileSync(join(WEB, 'sw.js'), body);
console.log(`sw.js: ${files.length} shell files, version ${VERSION}`);
