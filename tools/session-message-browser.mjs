import assert from 'node:assert/strict';
import { browserFixture } from './browserFixture.mjs';
const html = `<!doctype html><html><body><div id="app"></div><script type="module">
import {createApp,h,ref,provide} from 'vue';import {createRouter,createMemoryHistory} from 'vue-router';import {TooltipProvider} from 'reka-ui';
import Entry from '/src/features/sessions/entries/PeerMessageEntry.vue';
import Late from '/src/features/sessions/entries/LateAnswerEntry.vue';
import Dialogs from '/src/features/sessions/ActivityDialogs.vue';
import {openActivityKey} from '/src/features/sessions/activityDialogs.ts';
import '/src/styles/tokens.css';import '/src/styles/base.css';import '/src/styles/components.css';
const router=createRouter({history:createMemoryHistory(),routes:[{path:'/:pathMatch(.*)*',component:{render:()=>null}}]});
const item={entry:{created_at:Date.now(),payload:{metadata:{source:'session_message',from:{kind:'session',id:'reviewer-id',name:'Reviewer'}},content:[{type:'text',text:'[Message from session "Reviewer" (reviewer-id)]\\nPlease review the patch.\\nKeep this second line.'}]}}};
const visible=ref(true),request=ref(null),late=ref(false);let serial=0;
createApp({setup(){provide(openActivityKey,r=>request.value={...r,requestId:++serial});return()=>h(TooltipProvider,{},()=>[visible.value?(late.value?h(Late,{item:{entry:{seq:8,payload:{metadata:{answers:[]}}}}}):h(Entry,{item})):null,h(Dialogs,{chips:[],session:'s',request:request.value,onDismiss:()=>request.value=null})]);}}).use(router).mount('#app');window.fixture={visible,late};
</script></body></html>`;
await browserFixture(html, async ({js,until,click,send})=>{
 await until('!!document.querySelector(".peer-card-open")','direct message card');
 assert.equal(await js('document.querySelector(".peer-card-author").textContent'),'Reviewer');
 assert.equal(await js('document.querySelector(".peer-card-author").getAttribute("href")'),'/s/reviewer-id');
 assert.equal(await js(`[...document.querySelectorAll('a')].filter(a=>a.getAttribute('href')?.startsWith('/g/')).length`),0);
 assert.ok(await js('document.querySelector(".peer-card-preview").textContent.includes("Please review the patch.")'));
 assert.equal(await js('document.querySelector(".peer-card-preview").textContent.includes("[Message from session")'),false);
 await click('.peer-card-open');
 await until('!!document.querySelector(".modal-card")','read received message');
 assert.ok(await js('document.querySelector(".peer-card-detail").textContent.includes("Keep this second line.")'));
 await js('fixture.visible.value=false');
 await until('!document.querySelector(".peer-card")','virtual row recycled');
 assert.equal(await js('!!document.querySelector(".peer-message-window")'),true);
 await send('Input.dispatchKeyEvent',{type:'keyDown',key:'Escape',code:'Escape',windowsVirtualKeyCode:27});
 await send('Input.dispatchKeyEvent',{type:'keyUp',key:'Escape',code:'Escape',windowsVirtualKeyCode:27});
 await until('!document.querySelector(".modal-card")','close message');
 await js('fixture.visible.value=true;fixture.late.value=true');
 await click('.history-chip');
 await until('!!document.querySelector(".late-answer-detail")','late answer opens');
 await js('fixture.visible.value=false');
 await until('!document.querySelector(".history-chip")','late answer row recycled');
 assert.equal(await js('!!document.querySelector(".late-answer-detail")'),true);
 console.log('Stable peer and late-answer dialogs survive row recycling. Direct session message: sender link, full body, no group link, dialog and Escape passed');
});
