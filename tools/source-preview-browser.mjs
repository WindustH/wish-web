import assert from 'node:assert/strict';
import { browserFixture } from './browserFixture.mjs';

const source = 'const title: string = "中文 😀";\r\nfunction hello() {\r\n\treturn title;\r\n}\r\n';
const html = `<!doctype html><html data-theme="dark"><body><div id="app"></div><script type="module">
import {createApp,h,ref,provide} from 'vue';import {TooltipProvider} from 'reka-ui';
import Source from '/src/domain/media/SourcePreview.vue';
import {replyContextKey} from '/src/domain/references/context.ts';
import {sourceRange,sourceSelection} from '/src/ui/sourceSelection.ts';
import {referenceDescription} from '/src/core/replyReferences.ts';
import '/src/styles/tokens.css';import '/src/styles/base.css';import '/src/styles/components.css';import '/src/styles/codeHighlight.css';
const text=ref(${JSON.stringify(source)}),name=ref('example.ts'),mime=ref('text/plain'),focus=ref();
window.references=[];window.images=[];
createApp({setup(){provide(replyContextKey,{session:ref('s'),revision:ref(0),add:async(ref,image)=>{window.references.push(ref);window.images.push(image?.size||0)}});return()=>h(TooltipProvider,{},()=>h('main',{style:'height:600px;width:600px;display:flex;'},[h(Source,{key:name.value,text:text.value,name:name.value,mime:mime.value,session:'s',blob:'a'.repeat(64),version:'v1',scroll:0,truncated:false,focus:focus.value})]));}}).mount('#app');
window.fixture={text,name,mime,focus};
window.select=(start,end)=>{const code=document.querySelector('.source-code code'),range=sourceRange(code,start,end);getSelection().removeAllRanges();getSelection().addRange(range);document.dispatchEvent(new Event('selectionchange'));return sourceSelection(code,text.value,range)};
window.describe=referenceDescription;
</script></body></html>`;
await browserFixture(html,async({js,until,click,send})=>{
  await until('!!document.querySelector(".source-code .hljs-keyword")','TypeScript syntax highlighting');
  assert.equal(await js('document.querySelector(".source-code code").textContent'),source,'highlighting preserves exact CRLF/Unicode offsets');
  assert.equal(await js('document.querySelector(".source-numbers").textContent'),'1\n2\n3\n4\n5');
  const start=source.indexOf('function'),end=source.indexOf('}\r\n');
  assert.deepEqual(await js(`select(${start},${end})`),{start,end,text:source.slice(start,end),lineStart:2,lineEnd:3});
  await until('!!document.querySelector(".source-quote")','quote action');
  const copied=await js(`(()=>{const data=new DataTransfer();document.querySelector('.source-scroll').dispatchEvent(new ClipboardEvent('copy',{bubbles:true,cancelable:true,clipboardData:data}));return data.getData('text/plain')})()`);
  assert.equal(copied,source.slice(start,end),'copy excludes gutter numbers');
  await click('.source-quote');
  await until('references.length===1','reference delivered to composer');
  assert.equal(await js('references[0].fileName'),'example.ts');
  assert.equal(await js('references[0].version'),'v1');
  assert.match(await js('describe(references[0])'),/lines=2:3/);
  await js('getSelection().removeAllRanges();fixture.focus.value={...references[0]}');
  await until(`getSelection().toString()===${JSON.stringify(source.slice(start,end))}`,'locate exact source reference');
  const load=async(name,text,mime='text/plain')=>{await js(`fixture.focus.value=undefined;fixture.name.value=${JSON.stringify(name)};fixture.text.value=${JSON.stringify(text)};fixture.mime.value=${JSON.stringify(mime)}`);await until(`document.querySelector('.source-code')?.getAttribute('aria-label')===${JSON.stringify(name)}`,'source opens by default');};
  const preview=async()=>{await js(`document.querySelector('.source-toolbar input[value=preview]').click()`);};
  await load('notes.md','# Heading\n\n**Bold** `code`');
  assert.equal(await js('!!document.querySelector(".source-markdown")'),false);
  await preview();
  await until('document.querySelector(".source-markdown h1")?.textContent==="Heading"','Markdown rendered preview');
  await load('example.html','<html><head id="attributed-head" lang="en"><style>h1{color:red}</style></head><body><h1>Preview</h1><script>parent.pwned=1<\/script><img src="https://invalid.example/never-load" onerror="parent.pwned=2"></body></html>');
  await preview();
  await until('!!document.querySelector("iframe")','HTML preview');
  const frame=await js(`(()=>{const e=document.querySelector('iframe');return{sandbox:e.getAttribute('sandbox'),srcdoc:e.srcdoc}})()`);
  assert.equal(frame.sandbox,'');assert.match(frame.srcdoc,/Content-Security-Policy/);assert.doesNotMatch(frame.srcdoc,/<script|onerror/);assert.equal(await js('window.pwned||0'),0);
  assert.match(frame.srcdoc, /<head[^>]*id="attributed-head"[^>]*><meta http-equiv="Content-Security-Policy"/);
  await load('diagram.svg','<svg xmlns="http://www.w3.org/2000/svg" width="400" height="300"><rect width="400" height="300" fill="orange"/><text x="30" y="90">SVG preview</text></svg>','image/svg+xml');
  await preview();
  await until('!!document.querySelector(".image-preview img")?.naturalWidth','SVG image preview');
  const rect=await js(`(()=>{const r=document.querySelector('.image-preview img').getBoundingClientRect();return{x:r.x,y:r.y,w:r.width,h:r.height}})()`);
  await send('Input.dispatchMouseEvent',{type:'mousePressed',button:'left',clickCount:1,x:rect.x+rect.w*.1,y:rect.y+rect.h*.1});
  await send('Input.dispatchMouseEvent',{type:'mouseMoved',button:'left',buttons:1,x:rect.x+rect.w*.6,y:rect.y+rect.h*.6});
  await send('Input.dispatchMouseEvent',{type:'mouseReleased',button:'left',clickCount:1,x:rect.x+rect.w*.6,y:rect.y+rect.h*.6});
  await until('!!document.querySelector(".region-reply-menu button")','SVG region quote menu');
  await click('.region-reply-menu button');
  await until('references.length===2','SVG region delivered');
  assert.equal(await js('references[1].region.unit'),'px');
  assert.ok(await js('images[1]')>0,'SVG crop produces an image');
  console.log('Source preview: highlighting, exact selection/copy/locate, Markdown/HTML preview and SVG crop passed');
});
